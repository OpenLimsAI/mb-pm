// Exercise real workspace components with the API-isolated synthetic fixture.
import { strict as assert } from 'node:assert'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const output = resolve(process.argv[2] || 'verification/knowledge-workspace')
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_BIN || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
page.setDefaultTimeout(10000)
const errors = [], requests = [], screens = []
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => { if (/\/api\/v1\//.test(request.url())) requests.push(request.url()) })
const nav = name => page.getByRole('navigation', { name: '知识源功能' }).getByRole('button', { name, exact: true })
async function capture(name) {
  await page.screenshot({ path: resolve(output, `${name}.png`) })
  const geometry = await page.evaluate(() => ({ width: innerWidth, contentWidth: document.documentElement.scrollWidth }))
  assert(geometry.contentWidth <= geometry.width + 1, `${name}: horizontal overflow`)
  screens.push({ name, ...geometry })
}
try {
  await page.goto('http://localhost:1234/scripts/fixtures/folder-imports/index.html?folder=all')
  await page.locator('.ksv-paper-row').first().waitFor()
  assert.deepEqual(await page.getByRole('navigation', { name: '知识源功能' }).getByRole('button').allTextContents(), ['资料库', '来源下载', '自动导入', '下载记录'])
  await capture('desktop-library')
  const firstRow = page.locator('.ksv-paper-row').first()
  const before = await firstRow.boundingBox()
  await firstRow.getByRole('checkbox').check()
  const after = await firstRow.boundingBox()
  assert(before && after && Math.abs(before.y - after.y) <= 1, 'selecting a paper must not push the list down')
  await capture('desktop-selection')
  await page.getByRole('button', { name: '取消选择', exact: true }).click()
  await page.getByRole('button', { name: /^上游工艺开发/ }).click()
  await page.getByRole('heading', { name: '上游工艺开发', exact: true }).waitFor()
  await page.getByRole('button', { name: '上传 PDF', exact: true }).first().click()
  assert.equal(await page.locator('.ksv-paper-row').count(), 0, 'intake replaces the document workspace')
  assert.equal(await page.getByLabel('收录目标文件夹', { exact: true }).inputValue(), 'topic')
  await capture('desktop-upload')
  await page.getByRole('button', { name: '关闭添加资料', exact: true }).click()
  await page.locator('.ksv-paper-row').first().waitFor()
  await nav('来源下载').click()
  await page.getByRole('heading', { name: /可下载论文/ }).waitFor()
  assert.equal(await page.locator('.kso-sidebar').count(), 0, 'website downloads should not show the library sidebar')
  const sourceRow = page.locator('.kso-catalog-row').first()
  const sourceBefore = await sourceRow.boundingBox()
  await sourceRow.getByRole('checkbox').check()
  const sourceAfter = await sourceRow.boundingBox()
  assert(Math.abs(sourceBefore.y - sourceAfter.y) <= 1, 'source selection must not shift rows')
  await sourceRow.getByRole('checkbox').uncheck()
  const sourceSettings = page.locator('.kso-source-settings>summary')
  await sourceSettings.click()
  await page.getByRole('combobox', { name: /定期检查频率/ }).selectOption('weekly')
  await sourceSettings.click()
  assert(await page.getByText('有未保存修改', { exact: true }).isVisible(), 'unsaved changes remain visible when collapsed')
  await sourceSettings.click()
  await page.getByRole('combobox', { name: /定期检查频率/ }).selectOption('off')
  await sourceSettings.click()
  await capture('desktop-sources')
  await nav('自动导入').click()
  const settings = page.getByRole('button', { name: '自动导入设置 研究资料自动归档', exact: true })
  await settings.waitFor()
  assert.equal((await settings.innerText()).trim(), '自动导入设置')
  assert.equal(await settings.locator('svg').count(), 0, 'settings must be a text action')
  await capture('desktop-imports')
  await settings.click()
  await page.getByRole('form', { name: '自动导入设置', exact: true }).waitFor()
  await capture('desktop-import-settings')
  await page.getByRole('button', { name: '返回自动导入', exact: true }).click()
  await nav('下载记录').click()
  await page.getByRole('heading', { name: '下载任务', exact: true }).waitFor()
  await capture('desktop-downloads')

  await page.setViewportSize({ width: 390, height: 844 })
  await nav('资料库').click()
  await page.locator('.ksv-paper-row').first().waitFor()
  const tabBoxes = await Promise.all(['资料库','来源下载','自动导入','下载记录'].map(name => nav(name).boundingBox()))
  assert(tabBoxes.every(box => box && Math.abs(box.y - tabBoxes[0].y) <= 1), 'mobile navigation stays on one row')
  const location = await page.getByRole('button', { name: '切换资料位置', exact: true }).boundingBox()
  const heading = await page.getByRole('heading', { name: '上游工艺开发', exact: true }).boundingBox()
  assert(location && heading && heading.y >= location.y + location.height, 'mobile location switch must not overlap the heading')
  await capture('mobile-library')
  await page.getByRole('button', { name: '切换资料位置', exact: true }).click()
  await page.getByRole('button', { name: /^待整理/ }).waitFor({ state: 'visible' })
  await capture('mobile-folders')
  await page.getByRole('button', { name: /^待整理/ }).click()
  assert.equal(await page.getByRole('button', { name: '切换资料位置', exact: true }).getAttribute('aria-expanded'), 'false')
  await page.locator('.ksv-paper-row').first().waitFor()
  await capture('mobile-inbox')
  await nav('自动导入').click()
  await settings.waitFor()
  await capture('mobile-imports')
  await settings.click()
  await capture('mobile-import-settings')
  await nav('来源下载').click()
  await page.getByRole('heading', { name: /可下载论文/ }).waitFor()
  await capture('mobile-sources')
  assert.deepEqual(errors, [], 'page errors')
  assert.deepEqual(requests, [], 'synthetic fixture must not contact real APIs')
  writeFileSync(resolve(output, 'result.json'), JSON.stringify({ screens, errors, realApiRequests: requests, stableSelection: true, mobileNavigationSingleRow: true }, null, 2))
  console.log(JSON.stringify({ screens: screens.length, errors, realApiRequests: requests.length, stableSelection: true, mobileNavigationSingleRow: true }))
} finally {
  await browser.close()
}
