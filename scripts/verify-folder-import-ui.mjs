// Development-only visual acceptance against the synthetic, API-isolated fixture.
import { strict as assert } from 'node:assert'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const output = resolve(process.argv[2] || 'verification/folder-import-ui')
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_BIN || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
const errors = [], requests = [], geometry = []
page.on('pageerror', error => errors.push(error.message))
page.on('request', request => { if (/\/api\/v1\//.test(request.url())) requests.push(request.url()) })
async function capture(name) {
  await page.screenshot({ path: resolve(output, `${name}.png`), fullPage: false })
  const box = await page.evaluate(() => ({ width: innerWidth, contentWidth: document.documentElement.scrollWidth, headings: [...document.querySelectorAll('h1,h2')].map(e => e.textContent) }))
  geometry.push({ name, ...box })
  assert(box.contentWidth <= box.width + 1, `${name}: horizontal overflow`)
}
try {
  await page.goto('http://localhost:1234/scripts/fixtures/folder-imports/index.html?view=imports')
  await page.getByRole('heading', { name: '自动导入', exact: true }).waitFor()
  await page.getByRole('button', { name: '研究资料自动归档', exact: true }).waitFor()
  await capture('desktop-list')
  await page.getByRole('button', { name: '研究资料自动归档', exact: true }).click()
  await page.getByRole('heading', { name: '运行记录', exact: true }).waitFor()
  await capture('desktop-results')
  await page.getByRole('button', { name: '自动导入设置 研究资料自动归档', exact: true }).click()
  await page.getByRole('form', { name: '自动导入设置', exact: true }).waitFor()
  assert.equal(await page.locator('.kso-import-task').count(), 0, 'settings replace the task list')
  assert.equal(await page.locator('.kso-setup-section-fields').count(), 0, 'editing starts with summaries')
  await capture('desktop-settings')
  await page.getByRole('button', { name: '更改扫描时间', exact: true }).click()
  await page.getByRole('radio', { name: '每周', exact: true }).check()
  await page.getByLabel('每周扫描日期', { exact: true }).selectOption('6')
  await page.getByLabel('扫描时间', { exact: true }).fill('21:30')
  await capture('desktop-edit-schedule')
  await page.getByRole('button', { name: '更改保存位置', exact: true }).click()
  assert.equal(await page.getByLabel('扫描时间', { exact: true }).count(), 0, 'only one editor is open')
  await page.getByLabel('自动导入目标文件夹', { exact: true }).selectOption('analysis')
  await page.getByRole('button', { name: '保存设置', exact: true }).click()
  await page.getByText('自动导入设置已保存。', { exact: true }).waitFor()
  await page.getByRole('button', { name: '新建自动导入', exact: true }).click()
  await page.getByRole('radio', { name: '服务器 / NAS', exact: true }).check()
  await page.getByLabel('服务器子目录', { exact: true }).fill('papers')
  await capture('desktop-create-source')
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await page.getByLabel('自动导入目标文件夹', { exact: true }).selectOption('topic')
  await capture('desktop-create-destination')
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await capture('desktop-create-schedule')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '连接电脑', exact: true }).click()
  await page.getByRole('heading', { name: '连接我的电脑', exact: true }).waitFor()
  await capture('desktop-connection')
  await page.getByRole('button', { name: '关闭电脑连接', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '自动导入设置 研究资料自动归档', exact: true }).click()
  await capture('mobile-settings')
  await page.getByRole('button', { name: '更改扫描时间', exact: true }).click()
  await capture('mobile-edit-schedule')
  const saveBox = await page.getByRole('button', { name: '保存设置', exact: true }).boundingBox()
  assert(saveBox && saveBox.y >= 0 && saveBox.y + saveBox.height <= 844, 'mobile save button stays in view')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '新建自动导入', exact: true }).click()
  await capture('mobile-create-source')
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await capture('mobile-create-destination')
  await page.getByRole('button', { name: '下一步', exact: true }).click()
  await capture('mobile-create-schedule')
  assert.deepEqual(errors, [], 'page errors')
  assert.deepEqual(requests, [], 'synthetic fixture must not contact real APIs')
  writeFileSync(resolve(output, 'result.json'), JSON.stringify({ geometry, errors, realApiRequests: requests }, null, 2))
  console.log(JSON.stringify({ screens: geometry.length, noHorizontalOverflow: true, realApiRequests: requests.length, errors }))
} finally {
  await browser.close()
}
